#!/usr/bin/env node
/**
 * Build a mountable values.yml from a running dashboard's own topology.
 *
 *   node apps/api/scripts/values-from-dashboard.mjs https://dashboard-api.example.com \
 *     > /tmp/helm/core/values.yml
 *
 * `GET /api/config/routers` is the topology the dashboard already publishes,
 * and it is **already redacted**: the api masks every node url to scheme+host
 * before it leaves, because that is where provider api keys live. So this
 * needs no redaction step of its own — it is reading the safe projection, not
 * the file.
 *
 * What it is for: running the analysis against a real deployment's roles and
 * addons without anyone handing over the real chart values. Roles and addons
 * are the two facts that answer "why did failover not save it", and neither is
 * a secret.
 *
 * The urls it emits are placeholders. The parser DROPS an endpoint with no
 * url, and everything downstream masks to scheme+host anyway, so nothing that
 * reads this file can tell the difference.
 */
import { stringify } from "yaml";

const base = process.argv[2];
if (!base) {
  console.error(
    "usage: node apps/api/scripts/values-from-dashboard.mjs <dashboard-api-url> > values.yml\n" +
      "  the api url is in the web's GET /api/config as `apiUrl`",
  );
  process.exit(2);
}

const url = new URL("/api/config/routers", base);
const res = await fetch(url, { headers: { "user-agent": "curl/8.7" } });
if (!res.ok) {
  console.error(`${url} → HTTP ${res.status}`);
  process.exit(1);
}

const { routers = [] } = await res.json();
if (routers.length === 0) {
  console.error("that deployment publishes no routers — it has no values file mounted either");
  process.exit(1);
}

let nodes = 0;
let endpoints = 0;

const out = routers.map((r) => ({
  id: r.id,
  network: String(r.spec ?? r.id ?? "").toLowerCase(),
  nodes: (r.nodes ?? []).map((n) => {
    nodes += 1;
    return {
      name: n.name,
      is_backup: Boolean(n.isBackup),
      endpoints: (n.endpoints ?? []).map((e, i) => {
        endpoints += 1;
        return {
          // Placeholder by construction — see the header. The real one was
          // already masked to scheme+host before it reached us.
          url: `https://${String(n.name).toLowerCase().replace(/[^a-z0-9-]/g, "")}-${i}.redacted.invalid`,
          ...(e.interface ? { interface: e.interface } : {}),
          ...(Array.isArray(e.addons) && e.addons.length ? { addons: e.addons } : {}),
          ...(e.internalPath ? { internal_path: e.internalPath } : {}),
        };
      }),
    };
  }),
}));

process.stdout.write(
  `# Generated by values-from-dashboard.mjs from ${base}\n` +
    "# Roles and addons are real; urls are placeholders. The source endpoint\n" +
    "# masks urls to scheme+host before publishing them, so no key was read.\n" +
    stringify({ routers: out }),
);

console.error(`\n${routers.length} routers · ${nodes} nodes · ${endpoints} endpoints\n`);
